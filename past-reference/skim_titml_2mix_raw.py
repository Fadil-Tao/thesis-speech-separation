# Training function
def train_epoch(model, train_loader, optimizer, device, epoch):
    model.train()
    total_loss = 0
    num_batches = len(train_loader)

    pbar = tqdm(train_loader, desc=f'Epoch {epoch} [Train]')
    for batch_idx, batch in enumerate(pbar):
        # Move to device
        mix = batch['mix'].to(device)  # [batch, time]
        s1 = batch['s1'].to(device)    # [batch, time]
        s2 = batch['s2'].to(device)    # [batch, time]

        # Prepare inputs for ESPnet model
        batch_size = mix.size(0)
        mix_lengths = torch.full((batch_size,), mix.size(1), dtype=torch.long, device=device)

        # ESPnet expects 2D input [batch, time] - encoder adds channel dimension internally
        speech_ref1 = s1  # [batch, time]
        speech_ref2 = s2  # [batch, time]
        ref_lengths = mix_lengths.clone()

        # Forward pass - ESPnet model computes loss internally with PIT
        loss, stats, weight = model(
            speech_mix=mix,
            speech_mix_lengths=mix_lengths,
            speech_ref1=speech_ref1,
            speech_ref1_lengths=ref_lengths,
            speech_ref2=speech_ref2,
            speech_ref2_lengths=ref_lengths
        )

        # Backward pass
        optimizer.zero_grad()
        loss.backward()

        # Gradient clipping
        torch.nn.utils.clip_grad_norm_(model.parameters(), GRADIENT_CLIP)

        optimizer.step()

        # Accumulate loss
        total_loss += loss.item()

        # Update progress bar
        pbar.set_postfix({'loss': f'{loss.item():.4f}'})

    avg_loss = total_loss / num_batches
    return avg_loss

print("✓ Training function defined")

