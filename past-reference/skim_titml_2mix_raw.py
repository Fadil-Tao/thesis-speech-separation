# Custom Dataset class for IndonesianMix
class IndonesianMixDataset(Dataset):
    """
    Dataset for TITML-IDN-mix Indonesian speech separation

    Structure:
    - mix/: mixed audio files
    - s1/: source 1 (speaker 1)
    - s2/: source 2 (speaker 2)
    - metadata.json: dataset metadata
    """

    def __init__(self, data_dir, split='train', sample_rate=16000, max_length=64000):
        self.data_dir = Path(data_dir)
        self.split = split
        self.sample_rate = sample_rate
        self.max_length = max_length  # Fixed length (4 seconds at 16kHz)

        # Load metadata
        metadata_path = self.data_dir / 'metadata.json'
        with open(metadata_path, 'r') as f:
            self.metadata = json.load(f)

        # Get file list
        mix_dir = self.data_dir / 'mix'
        self.file_list = sorted([f.stem for f in mix_dir.glob('*.wav')])

        print(f"Loaded {split} split: {len(self.file_list)} samples")
        print(f"Fixed length: {max_length} samples ({max_length/sample_rate:.1f}s)")

    def __len__(self):
        return len(self.file_list)

    def _pad_or_truncate(self, audio):
        """Pad or truncate audio to fixed length"""
        if len(audio) > self.max_length:
            # Truncate
            audio = audio[:self.max_length]
        elif len(audio) < self.max_length:
            # Pad with zeros
            padding = self.max_length - len(audio)
            audio = np.pad(audio, (0, padding), mode='constant')
        return audio

    def __getitem__(self, idx):
        file_id = self.file_list[idx]

        # Load audio files
        mix_path = self.data_dir / 'mix' / f'{file_id}.wav'
        s1_path = self.data_dir / 's1' / f'{file_id}.wav'
        s2_path = self.data_dir / 's2' / f'{file_id}.wav'

        mix, sr_mix = sf.read(mix_path)
        s1, sr_s1 = sf.read(s1_path)
        s2, sr_s2 = sf.read(s2_path)

        # Ensure consistent sample rate
        assert sr_mix == self.sample_rate, f"Expected {self.sample_rate}Hz, got {sr_mix}Hz"

        # Pad or truncate to fixed length
        mix = self._pad_or_truncate(mix)
        s1 = self._pad_or_truncate(s1)
        s2 = self._pad_or_truncate(s2)

        # Convert to torch tensors
        mix_tensor = torch.FloatTensor(mix)
        s1_tensor = torch.FloatTensor(s1)
        s2_tensor = torch.FloatTensor(s2)

        return {
            'mix': mix_tensor,
            's1': s1_tensor,
            's2': s2_tensor,
            'file_id': file_id
        }

