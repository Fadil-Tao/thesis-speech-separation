class SkiMAttentionSeparator(AbsSeparator):
    """SkiM Separator with MemAttention replacing Mem-LSTM.

    Args:
        input_dim:      input feature dimension (must match encoder channel)
        causal:         causal (online) mode
        num_spk:        number of target speakers
        predict_noise:  whether to output a noise estimate
        nonlinear:      mask activation — 'relu', 'tanh', or 'sigmoid'
        layer:          number of SkiM blocks
        unit:           hidden size of SegLSTM
        segment_size:   frames per segment for SegLSTM
        dropout:        dropout probability
        mem_type:       'hc', 'h', 'c', 'id' — which LSTM states MemAttention processes
        seg_overlap:    50% segment overlap (non-causal only)
        num_heads:      attention heads in MemAttention (must divide `unit`)
    """

    def __init__(
        self,
        input_dim: int,
        causal: bool = True,
        num_spk: int = 2,
        predict_noise: bool = False,
        nonlinear: str = "relu",
        layer: int = 3,
        unit: int = 512,
        segment_size: int = 20,
        dropout: float = 0.0,
        mem_type: str = "hc",
        seg_overlap: bool = False,
        num_heads: int = 4,
    ):
        super().__init__()
        self._num_spk       = num_spk
        self.predict_noise  = predict_noise
        self.segment_size   = segment_size

        if mem_type not in ("hc", "h", "c", "id", None):
            raise ValueError(f"Not supporting mem_type={mem_type}")

        self.num_outputs = self.num_spk + 1 if self.predict_noise else self.num_spk
        self.skim = SkiM(
            input_size=input_dim,
            hidden_size=unit,
            output_size=input_dim * self.num_outputs,
            dropout=dropout,
            num_blocks=layer,
            bidirectional=(not causal),
            norm_type="cLN" if causal else "gLN",
            segment_size=segment_size,
            seg_overlap=seg_overlap,
            mem_type=mem_type,
            num_heads=num_heads,
        )

        if nonlinear not in ("sigmoid", "relu", "tanh"):
            raise ValueError(f"Not supporting nonlinear={nonlinear}")
        self.nonlinear = {"sigmoid": nn.Sigmoid(), "relu": nn.ReLU(), "tanh": nn.Tanh()}[nonlinear]

    def forward(
        self,
        input: Union[torch.Tensor, ComplexTensor],
        ilens: torch.Tensor,
        additional: Optional[Dict] = None,
    ) -> Tuple[List[Union[torch.Tensor, ComplexTensor]], torch.Tensor, OrderedDict]:
        feature = abs(input) if is_complex(input) else input
        B, T, N = feature.shape

        processed = self.skim(feature)              # B, T, N*num_outputs
        processed = processed.view(B, T, N, self.num_outputs)
        masks = self.nonlinear(processed).unbind(dim=3)

        if self.predict_noise:
            *masks, mask_noise = masks

        masked = [input * m for m in masks]
        others = OrderedDict(
            zip([f"mask_spk{i+1}" for i in range(len(masks))], masks)
        )
        if self.predict_noise:
            others["noise1"] = input * mask_noise

        return masked, ilens, others

    def forward_streaming(self, input_frame: torch.Tensor, states=None):
        feature = abs(input_frame) if is_complex(input_frame) else input_frame
        B, _, N = feature.shape

        processed, states = self.skim.forward_stream(feature, states=states)
        processed = processed.view(B, 1, N, self.num_outputs)
        masks = self.nonlinear(processed).unbind(dim=3)

        if self.predict_noise:
            *masks, mask_noise = masks

        masked = [input_frame * m for m in masks]
        others = OrderedDict(
            zip([f"mask_spk{i+1}" for i in range(len(masks))], masks)
        )
        if self.predict_noise:
            others["noise1"] = input_frame * mask_noise

        return masked, states, others

    @property
    def num_spk(self):
        return self._num_spk


