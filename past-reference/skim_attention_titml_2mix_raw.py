# Metric helper functions
def si_snr_loss(estimate, target, eps=1e-8):
    """SI-SNR as a loss (negative, for PIT permutation selection)"""
    estimate = estimate - estimate.mean(dim=-1, keepdim=True)
    target   = target   - target.mean(dim=-1,   keepdim=True)
    s_target = (torch.sum(estimate * target, dim=-1, keepdim=True) * target) / \
               (torch.sum(target ** 2, dim=-1, keepdim=True) + eps)
    e_noise  = estimate - s_target
    si_snr   = 10 * torch.log10(
        (torch.sum(s_target ** 2, dim=-1) + eps) /
        (torch.sum(e_noise  ** 2, dim=-1) + eps)
    )
    return -si_snr.mean()

def calculate_si_snr(estimate, target, eps=1e-8):
    """SI-SNR metric (positive dB value)"""
    estimate = estimate - estimate.mean(dim=-1, keepdim=True)
    target   = target   - target.mean(dim=-1,   keepdim=True)
    s_target = (torch.sum(estimate * target, dim=-1, keepdim=True) * target) / \
               (torch.sum(target ** 2, dim=-1, keepdim=True) + eps)
    e_noise  = estimate - s_target
    si_snr   = 10 * torch.log10(
        (torch.sum(s_target ** 2, dim=-1) + eps) /
        (torch.sum(e_noise  ** 2, dim=-1) + eps)
    )
    return si_snr

