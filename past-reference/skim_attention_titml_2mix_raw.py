def evaluate_test_set(model, test_loader, device):
    model.eval()

    all_si_snr_mix     = []
    all_si_snr_est     = []
    all_si_snr_improve = []
    all_sdr_mix        = [] if COMPUTE_SDR else None
    all_sdr_est        = [] if COMPUTE_SDR else None

    with torch.no_grad():
        pbar = tqdm(test_loader, desc='Evaluating Test Set')
        for batch in pbar:
            mix = batch['mix'].to(device)
            s1  = batch['s1'].to(device)
            s2  = batch['s2'].to(device)

            targets     = torch.stack([s1, s2], dim=1)
            mix_lengths = torch.full((mix.size(0),), mix.size(1), dtype=torch.long, device=device)

            separated_output = model.forward_enhance(mix, mix_lengths)

            if isinstance(separated_output, (tuple, list)):
                estimates = separated_output[0]
            else:
                estimates = separated_output

            if isinstance(estimates, (list, tuple)):
                estimates = torch.stack(list(estimates), dim=1)

            while estimates.dim() > 3:
                estimates = estimates.squeeze(2)

            # PIT permutation selection
            perm_losses = []
            for perm in [(0, 1), (1, 0)]:
                loss = sum(si_snr_loss(estimates[:, i], targets[:, j]) for i, j in enumerate(perm))
                perm_losses.append(loss)
            best_perm = [(0, 1), (1, 0)][torch.argmin(torch.stack(perm_losses)).item()]

            for b in range(mix.size(0)):
                # SI-SNR of mixture (baseline)
                si_snr_mix = ((calculate_si_snr(mix[b:b+1], s1[b:b+1]) +
                               calculate_si_snr(mix[b:b+1], s2[b:b+1])) / 2)
                all_si_snr_mix.append(si_snr_mix.item())

                # SI-SNR of estimates
                est_s1 = estimates[b:b+1, best_perm[0]]
                est_s2 = estimates[b:b+1, best_perm[1]]
                si_snr_est = ((calculate_si_snr(est_s1, s1[b:b+1]) +
                               calculate_si_snr(est_s2, s2[b:b+1])) / 2)
                all_si_snr_est.append(si_snr_est.item())
                all_si_snr_improve.append((si_snr_est - si_snr_mix).item())

                if COMPUTE_SDR:
                    targets_np = torch.stack([s1[b], s2[b]]).cpu().numpy()
                    mix_np     = np.stack([mix[b].cpu().numpy(), mix[b].cpu().numpy()])
                    est_np     = torch.stack([est_s1[0], est_s2[0]]).cpu().numpy()
                    sdr_mix, _, _, _ = bss_eval_sources(targets_np, mix_np,  compute_permutation=False)
                    sdr_est, _, _, _ = bss_eval_sources(targets_np, est_np,  compute_permutation=False)
                    all_sdr_mix.append(sdr_mix.mean())
                    all_sdr_est.append(sdr_est.mean())

    results = {
        'SI-SNR_mix': np.mean(all_si_snr_mix),
        'SI-SNR_est': np.mean(all_si_snr_est),
        'SI-SNRi':    np.mean(all_si_snr_improve),
    }
    if COMPUTE_SDR:
        results['SDR_mix'] = np.mean(all_sdr_mix)
        results['SDR_est'] = np.mean(all_sdr_est)
        results['SDRi']    = np.mean(all_sdr_est) - np.mean(all_sdr_mix)

    return results


